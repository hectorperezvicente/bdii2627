-- Mínimos de ALUMNO (se validan al COMMIT).
ALTER TABLE ALUMNO ADD CONSTRAINT FK_ALUMNO_TELEFONO_REF
    FOREIGN KEY (DNI, TELEFONO_REF) REFERENCES TELEFONO_ALUMNO (DNI, TELEFONO)
    DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE ALUMNO ADD CONSTRAINT FK_ALUMNO_TUTELA_REF
    FOREIGN KEY (DNI_TUTOR_REF, DNI) REFERENCES TUTELA (DNI_TUTOR, DNI_ALUMNO)
    DEFERRABLE INITIALLY DEFERRED;

-- ---- DESTINATARIO (categoría: ALUMNO o TUTOR_LEGAL) ------------------------
-- Cada destinatario tiene EXACTAMENTE un origen (CK_DESTINATARIO_ORIGEN) y cada
-- persona como mucho un destinatario (UQ por origen). Las FK van de
-- DESTINATARIO hacia la persona de origen.
CREATE TABLE DESTINATARIO (
    ID_DESTINATARIO  NUMBER GENERATED ALWAYS AS IDENTITY,
    DNI_ALUMNO       VARCHAR2(10),
    DNI_TUTOR        VARCHAR2(10),
    CONSTRAINT PK_DESTINATARIO PRIMARY KEY (ID_DESTINATARIO),
    CONSTRAINT UQ_DESTINATARIO_ALUMNO UNIQUE (DNI_ALUMNO),
    CONSTRAINT UQ_DESTINATARIO_TUTOR  UNIQUE (DNI_TUTOR),
    CONSTRAINT UQ_DESTINATARIO_ID_ALUMNO UNIQUE (ID_DESTINATARIO, DNI_ALUMNO),  -- destino FK INCIDENCIA
    CONSTRAINT UQ_DESTINATARIO_ID_TUTOR  UNIQUE (ID_DESTINATARIO, DNI_TUTOR),   -- destino FK INCIDENCIA
    CONSTRAINT FK_DESTINATARIO_ALUMNO FOREIGN KEY (DNI_ALUMNO)
        REFERENCES ALUMNO (DNI) ON DELETE CASCADE,
    CONSTRAINT FK_DESTINATARIO_TUTOR FOREIGN KEY (DNI_TUTOR)
        REFERENCES TUTOR_LEGAL (DNI_TUTOR) ON DELETE CASCADE,
    CONSTRAINT CK_DESTINATARIO_ORIGEN CHECK (
        (DNI_ALUMNO IS NOT NULL AND DNI_TUTOR IS NULL)
     OR (DNI_ALUMNO IS NULL AND DNI_TUTOR IS NOT NULL))
);

-- ---- INCIDENCIA (entidad débil de ALUMNO) con NOTIFICA (1:N) fusionada -----
-- RN-04: el destinatario es el propio alumno protagonista (DNI_ALUMNO_DEST) o
-- un tutor que lo tutela (DNI_TUTOR_DEST). Exactamente una de las dos columnas.
--   FK_INCIDENCIA_DEST_ALUMNO / _DEST_TUTOR: el destinatario corresponde a esa persona.
--   CK_INCIDENCIA_DEST: si es el alumno, ha de ser el protagonista.
--   FK_INCIDENCIA_TUTELA: si es un tutor, ha de tutelar al protagonista.
-- Las FK compuestas con alguna columna NULL no se evalúan (Oracle), por eso
-- solo actúa la rama que corresponde.
CREATE TABLE INCIDENCIA (
    DNI_ALUMNO          VARCHAR2(10),
    NUM_INCIDENCIA      NUMBER(5),
    FECHA               DATE           NOT NULL,
    DESCRIPCION         VARCHAR2(300)  NOT NULL,
    GRAVEDAD            VARCHAR2(10)   NOT NULL,
    FECHA_NOTIFICACION  DATE           NOT NULL,
    ID_DESTINATARIO     NUMBER         NOT NULL,
    DNI_ALUMNO_DEST     VARCHAR2(10),
    DNI_TUTOR_DEST      VARCHAR2(10),
    CONSTRAINT PK_INCIDENCIA PRIMARY KEY (DNI_ALUMNO, NUM_INCIDENCIA),
    CONSTRAINT FK_INCIDENCIA_ALUMNO FOREIGN KEY (DNI_ALUMNO)
        REFERENCES ALUMNO (DNI) ON DELETE CASCADE,   -- al borrar el alumno desaparecen sus incidencias
    CONSTRAINT FK_INCIDENCIA_DEST_ALUMNO FOREIGN KEY (ID_DESTINATARIO, DNI_ALUMNO_DEST)
        REFERENCES DESTINATARIO (ID_DESTINATARIO, DNI_ALUMNO),
    CONSTRAINT FK_INCIDENCIA_DEST_TUTOR FOREIGN KEY (ID_DESTINATARIO, DNI_TUTOR_DEST)
        REFERENCES DESTINATARIO (ID_DESTINATARIO, DNI_TUTOR),
    CONSTRAINT FK_INCIDENCIA_TUTELA FOREIGN KEY (DNI_TUTOR_DEST, DNI_ALUMNO)
        REFERENCES TUTELA (DNI_TUTOR, DNI_ALUMNO),   -- restrictiva: no se borra una tutela usada
    CONSTRAINT CK_INCIDENCIA_NUM CHECK (NUM_INCIDENCIA > 0),
    CONSTRAINT CK_INCIDENCIA_GRAVEDAD CHECK (GRAVEDAD IN ('LEVE','GRAVE','MUY_GRAVE')),
    CONSTRAINT CK_INCIDENCIA_NOTIF CHECK (FECHA_NOTIFICACION >= FECHA),
    CONSTRAINT CK_INCIDENCIA_DEST CHECK (
        (DNI_ALUMNO_DEST IS NOT NULL AND DNI_TUTOR_DEST IS NULL AND DNI_ALUMNO_DEST = DNI_ALUMNO)
     OR (DNI_ALUMNO_DEST IS NULL AND DNI_TUTOR_DEST IS NOT NULL))
);

-- ---- MATRICULA (N:M ALUMNO - GRUPO) ---------------------------------------
-- CURSO_ACADEMICO se conserva aquí para: (1) FK compuesta (grupo, curso) que
-- garantiza que el curso coincide con el del grupo; (2) UNIQUE (alumno, curso):
-- un solo grupo por curso, permitiendo guardar el historial de cursos distintos.
CREATE TABLE MATRICULA (
    DNI_ALUMNO       VARCHAR2(10),
    ID_GRUPO         VARCHAR2(10),
    CURSO_ACADEMICO  VARCHAR2(9)   NOT NULL,
    CONSTRAINT PK_MATRICULA PRIMARY KEY (DNI_ALUMNO, ID_GRUPO),
    CONSTRAINT UQ_MATRICULA_ALUMNO_CURSO UNIQUE (DNI_ALUMNO, CURSO_ACADEMICO),
    CONSTRAINT FK_MATRICULA_ALUMNO FOREIGN KEY (DNI_ALUMNO)
        REFERENCES ALUMNO (DNI),
    CONSTRAINT FK_MATRICULA_GRUPO FOREIGN KEY (ID_GRUPO, CURSO_ACADEMICO)
        REFERENCES GRUPO (ID_GRUPO, CURSO_ACADEMICO)
);

-- ---- ASIGNATURA -----------------------------------------------------------
CREATE TABLE ASIGNATURA (
    COD_ASIGNATURA  VARCHAR2(10),
    NOMBRE          VARCHAR2(40)  NOT NULL,
    CONSTRAINT PK_ASIGNATURA PRIMARY KEY (COD_ASIGNATURA)
);

-- ---- IMPARTE (ternaria ASIGNATURA - PROFESOR - GRUPO; agregación) ----------
CREATE TABLE IMPARTE (
    COD_ASIGNATURA  VARCHAR2(10),
    NSS_PROFESOR    VARCHAR2(12),
    ID_GRUPO        VARCHAR2(10),
    CARGA_HORARIA   NUMBER(2)  NOT NULL,       -- horas semanales
    CONSTRAINT PK_IMPARTE PRIMARY KEY (COD_ASIGNATURA, NSS_PROFESOR, ID_GRUPO),
    CONSTRAINT FK_IMPARTE_ASIGNATURA FOREIGN KEY (COD_ASIGNATURA)
        REFERENCES ASIGNATURA (COD_ASIGNATURA),
    CONSTRAINT FK_IMPARTE_PROFESOR FOREIGN KEY (NSS_PROFESOR)
        REFERENCES PROFESOR (NSS),
    CONSTRAINT FK_IMPARTE_GRUPO FOREIGN KEY (ID_GRUPO)
        REFERENCES GRUPO (ID_GRUPO),
    CONSTRAINT CK_IMPARTE_CARGA CHECK (CARGA_HORARIA BETWEEN 1 AND 40)
);

-- ---- EVALUA (relación sobre la agregación IMPARTE) -------------------------
