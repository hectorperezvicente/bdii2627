-- 1. TABLAS Y RESTRICCIONES
--
-- ACCIONES REFERENCIALES. Por defecto RESTRICTIVAS (sin cláusula) para no perder
-- histórico académico (matrículas, notas, docencia). Excepciones razonadas:
--   ON DELETE CASCADE
--     FK_PROFESOR_EMPLEADO, FK_PAS_EMPLEADO ....... la subclase es la misma entidad
--     FK_JEFE_PROFESOR, FK_TUTOR_GRUPO_PROFESOR ... un rol de profesor no existe sin el profesor
--     FK_SUSTITUYE_SUSTITUTO / _SUSTITUIDO ........ una sustitución no existe sin sus profesores
--     FK_PERIODO_SUSTITUYE ........................ atributo multivaluado de SUSTITUYE
--     FK_TELEFONO_ALUMNO .......................... atributo multivaluado de ALUMNO
--     FK_TUTELA_TUTOR / FK_TUTELA_ALUMNO .......... tabla puente sin vida propia
--     FK_DESTINATARIO_ALUMNO / _TUTOR ............. la categoría solo existe con la persona
--     FK_INCIDENCIA_ALUMNO ........................ entidad débil: depende de su propietario
--     FK_AULA_EDIFICIO ............................ entidad débil: depende de su propietario
--     FK_OCUPA_AULA ............................... tabla puente sin vida propia
--   ON DELETE SET NULL
--     FK_PAS_SUPERVISOR ........................... el supervisado sigue existiendo (mín 0)
--   RESTRICTIVAS relevantes: FK_INCIDENCIA_TUTELA (no se borra una tutela ya usada
--   en una notificación), FK_MATRICULA_*, FK_EVALUA_*, FK_IMPARTE_*, FK_OCUPA_GRUPO,
--   FK_PROFESOR_DEPARTAMENTO, FK_JEFE_DEPARTAMENTO.
-- ============================================================================

-- ---- EMPLEADO (superclase de la especialización DISJUNTA y TOTAL) ----------
-- TIPO + CK_EMPLEADO_SUBCLASE: cada empleado es de un único tipo (disyunción).
-- NSS_PROFESOR / NSS_PAS + FK diferidas (se crean más abajo): la fila de la
-- subclase correspondiente debe existir al COMMIT (totalidad).
CREATE TABLE EMPLEADO (
    NSS               VARCHAR2(12),
    NOMBRE            VARCHAR2(30)  NOT NULL,
    APELLIDOS         VARCHAR2(60)  NOT NULL,
    FECHA_NACIMIENTO  DATE          NOT NULL,
    SALARIO           NUMBER(8,2)   NOT NULL,
    TIPO              VARCHAR2(10)  NOT NULL,
    NSS_PROFESOR      VARCHAR2(12),
    NSS_PAS           VARCHAR2(12),
    CONSTRAINT PK_EMPLEADO PRIMARY KEY (NSS),
    CONSTRAINT UQ_EMPLEADO_NSS_TIPO UNIQUE (NSS, TIPO),   -- destino de FK (NSS, TIPO)
    CONSTRAINT CK_EMPLEADO_SALARIO CHECK (SALARIO > 0),
    CONSTRAINT CK_EMPLEADO_TIPO CHECK (TIPO IN ('PROFESOR','PAS')),
    CONSTRAINT CK_EMPLEADO_SUBCLASE CHECK (
        (TIPO = 'PROFESOR' AND NSS_PROFESOR IS NOT NULL AND NSS_PROFESOR = NSS AND NSS_PAS IS NULL)
     OR (TIPO = 'PAS'      AND NSS_PAS      IS NOT NULL AND NSS_PAS      = NSS AND NSS_PROFESOR IS NULL))
);

-- ---- DEPARTAMENTO (NSS_JEFE: mínimo "exactamente un jefe", FK diferida) -----
CREATE TABLE DEPARTAMENTO (
    COD_DEPARTAMENTO  VARCHAR2(10),
    NOMBRE            VARCHAR2(40)  NOT NULL,
    NSS_JEFE          VARCHAR2(12)  NOT NULL,
    CONSTRAINT PK_DEPARTAMENTO PRIMARY KEY (COD_DEPARTAMENTO)
);

-- ---- PROFESOR (subclase de EMPLEADO) --------------------------------------
-- La FK (NSS, TIPO) hacia EMPLEADO solo acepta empleados de tipo PROFESOR.
CREATE TABLE PROFESOR (
    NSS               VARCHAR2(12),
    TIPO              VARCHAR2(10)  DEFAULT 'PROFESOR' NOT NULL,
    FECHA_INGRESO     DATE          NOT NULL,
    COD_DEPARTAMENTO  VARCHAR2(10)  NOT NULL,
    CONSTRAINT PK_PROFESOR PRIMARY KEY (NSS),
    CONSTRAINT CK_PROFESOR_TIPO CHECK (TIPO = 'PROFESOR'),
    CONSTRAINT FK_PROFESOR_EMPLEADO FOREIGN KEY (NSS, TIPO)
        REFERENCES EMPLEADO (NSS, TIPO) ON DELETE CASCADE,
    CONSTRAINT FK_PROFESOR_DEPARTAMENTO FOREIGN KEY (COD_DEPARTAMENTO)
        REFERENCES DEPARTAMENTO (COD_DEPARTAMENTO)
);

-- ---- PAS (subclase de EMPLEADO; relación reflexiva SUPERVISA 1:N) ----------
CREATE TABLE PAS (
    NSS             VARCHAR2(12),
    TIPO            VARCHAR2(10)  DEFAULT 'PAS' NOT NULL,
    PUESTO          VARCHAR2(30)  NOT NULL,
    TURNO           VARCHAR2(10)  NOT NULL,
    NSS_SUPERVISOR  VARCHAR2(12),
    CONSTRAINT PK_PAS PRIMARY KEY (NSS),
    CONSTRAINT CK_PAS_TIPO CHECK (TIPO = 'PAS'),
    CONSTRAINT FK_PAS_EMPLEADO FOREIGN KEY (NSS, TIPO)
        REFERENCES EMPLEADO (NSS, TIPO) ON DELETE CASCADE,
    -- Si desaparece el supervisor, los supervisados quedan sin supervisor.
    CONSTRAINT FK_PAS_SUPERVISOR FOREIGN KEY (NSS_SUPERVISOR)
        REFERENCES PAS (NSS) ON DELETE SET NULL,
    CONSTRAINT CK_PAS_TURNO CHECK (TURNO IN ('MANANA','TARDE','PARTIDO','NOCHE')),
    CONSTRAINT CK_PAS_NO_AUTOSUPERVISION CHECK (NSS_SUPERVISOR IS NULL OR NSS_SUPERVISOR <> NSS)
);

-- Totalidad de la especialización: la fila de subclase debe existir al COMMIT.
ALTER TABLE EMPLEADO ADD CONSTRAINT FK_EMPLEADO_PROFESOR
    FOREIGN KEY (NSS_PROFESOR) REFERENCES PROFESOR (NSS)
    DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE EMPLEADO ADD CONSTRAINT FK_EMPLEADO_PAS
    FOREIGN KEY (NSS_PAS) REFERENCES PAS (NSS)
    DEFERRABLE INITIALLY DEFERRED;

-- ---- GRUPO ----------------------------------------------------------------
-- UQ_GRUPO_ID_CURSO: destino de la FK compuesta de MATRICULA (grupo-curso).
CREATE TABLE GRUPO (
    ID_GRUPO          VARCHAR2(10),
    CURSO_ACADEMICO   VARCHAR2(9)   NOT NULL,   -- formato 2025/2026
    CONSTRAINT PK_GRUPO PRIMARY KEY (ID_GRUPO),
    CONSTRAINT UQ_GRUPO_ID_CURSO UNIQUE (ID_GRUPO, CURSO_ACADEMICO),
    CONSTRAINT CK_GRUPO_CURSO CHECK (REGEXP_LIKE(CURSO_ACADEMICO, '^[0-9]{4}/[0-9]{4}$')),
    -- el segundo año es el siguiente al primero (CASE evita errores de conversión
    -- si el formato fuera incorrecto; de eso ya se ocupa CK_GRUPO_CURSO)
    CONSTRAINT CK_GRUPO_CURSO_CONSEC CHECK (
        CASE WHEN REGEXP_LIKE(CURSO_ACADEMICO, '^[0-9]{4}/[0-9]{4}$')
             THEN TO_NUMBER(SUBSTR(CURSO_ACADEMICO, 6, 4)) - TO_NUMBER(SUBSTR(CURSO_ACADEMICO, 1, 4))
        END = 1)
);

-- ---- JEFE_DEPARTAMENTO (subclase solapada de PROFESOR; DIRIGE 1:1) ---------
CREATE TABLE JEFE_DEPARTAMENTO (
    NSS                 VARCHAR2(12),
    COD_DEPARTAMENTO    VARCHAR2(10)  NOT NULL,
    FECHA_INICIO_CARGO  DATE          NOT NULL,
    CONSTRAINT PK_JEFE_DEPARTAMENTO PRIMARY KEY (NSS),
    CONSTRAINT UQ_JEFE_DEPARTAMENTO_DEPT UNIQUE (COD_DEPARTAMENTO),
    CONSTRAINT UQ_JEFE_NSS_DEPT UNIQUE (NSS, COD_DEPARTAMENTO),   -- destino de FK diferida
    CONSTRAINT FK_JEFE_PROFESOR FOREIGN KEY (NSS)
        REFERENCES PROFESOR (NSS) ON DELETE CASCADE,
    CONSTRAINT FK_JEFE_DEPARTAMENTO FOREIGN KEY (COD_DEPARTAMENTO)
        REFERENCES DEPARTAMENTO (COD_DEPARTAMENTO)
);

-- Mínimo: todo departamento tiene exactamente un jefe, y es el de ESE departamento.
ALTER TABLE DEPARTAMENTO ADD CONSTRAINT FK_DEPARTAMENTO_JEFE
    FOREIGN KEY (NSS_JEFE, COD_DEPARTAMENTO)
    REFERENCES JEFE_DEPARTAMENTO (NSS, COD_DEPARTAMENTO)
    DEFERRABLE INITIALLY DEFERRED;

-- ---- TUTOR_GRUPO (subclase solapada de PROFESOR; TUTORIZA 1:1) ------------
CREATE TABLE TUTOR_GRUPO (
    NSS       VARCHAR2(12),
    ID_GRUPO  VARCHAR2(10)  NOT NULL,
    CONSTRAINT PK_TUTOR_GRUPO PRIMARY KEY (NSS),
    CONSTRAINT UQ_TUTOR_GRUPO_GRUPO UNIQUE (ID_GRUPO),
    CONSTRAINT FK_TUTOR_GRUPO_PROFESOR FOREIGN KEY (NSS)
        REFERENCES PROFESOR (NSS) ON DELETE CASCADE,
    CONSTRAINT FK_TUTOR_GRUPO_GRUPO FOREIGN KEY (ID_GRUPO)
        REFERENCES GRUPO (ID_GRUPO)
);

-- ---- SUSTITUYE (reflexiva N:M de PROFESOR) y su atributo multivaluado ------
-- FECHA_PERIODO_REF: mínimo "toda sustitución tiene al menos un periodo".
CREATE TABLE SUSTITUYE (
    NSS_SUSTITUTO     VARCHAR2(12),
    NSS_SUSTITUIDO    VARCHAR2(12),
    FECHA_PERIODO_REF DATE          NOT NULL,
    CONSTRAINT PK_SUSTITUYE PRIMARY KEY (NSS_SUSTITUTO, NSS_SUSTITUIDO),
    CONSTRAINT FK_SUSTITUYE_SUSTITUTO FOREIGN KEY (NSS_SUSTITUTO)
        REFERENCES PROFESOR (NSS) ON DELETE CASCADE,
    CONSTRAINT FK_SUSTITUYE_SUSTITUIDO FOREIGN KEY (NSS_SUSTITUIDO)
        REFERENCES PROFESOR (NSS) ON DELETE CASCADE,
    CONSTRAINT CK_SUSTITUYE_DISTINTOS CHECK (NSS_SUSTITUTO <> NSS_SUSTITUIDO)
);

-- FECHA_FIN NULL = periodo de sustitución en curso (fecha de fin desconocida, RN-11).
CREATE TABLE PERIODO_SUSTITUCION (
    NSS_SUSTITUTO   VARCHAR2(12),
    NSS_SUSTITUIDO  VARCHAR2(12),
    FECHA_INICIO    DATE,
    FECHA_FIN       DATE,
    CONSTRAINT PK_PERIODO_SUSTITUCION PRIMARY KEY (NSS_SUSTITUTO, NSS_SUSTITUIDO, FECHA_INICIO),
    CONSTRAINT FK_PERIODO_SUSTITUYE FOREIGN KEY (NSS_SUSTITUTO, NSS_SUSTITUIDO)
        REFERENCES SUSTITUYE (NSS_SUSTITUTO, NSS_SUSTITUIDO) ON DELETE CASCADE,
    CONSTRAINT CK_PERIODO_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);

ALTER TABLE SUSTITUYE ADD CONSTRAINT FK_SUSTITUYE_PERIODO_REF
    FOREIGN KEY (NSS_SUSTITUTO, NSS_SUSTITUIDO, FECHA_PERIODO_REF)
    REFERENCES PERIODO_SUSTITUCION (NSS_SUSTITUTO, NSS_SUSTITUIDO, FECHA_INICIO)
    DEFERRABLE INITIALLY DEFERRED;

-- ---- TUTOR_LEGAL ----------------------------------------------------------
CREATE TABLE TUTOR_LEGAL (
