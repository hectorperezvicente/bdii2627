-- ---- TELEFONO_ALUMNO (atributo multivaluado) -------------------------------
CREATE TABLE TELEFONO_ALUMNO (
    DNI       VARCHAR2(10),
    TELEFONO  VARCHAR2(9),
    CONSTRAINT PK_TELEFONO_ALUMNO PRIMARY KEY (DNI, TELEFONO),
    CONSTRAINT FK_TELEFONO_ALUMNO FOREIGN KEY (DNI)
        REFERENCES ALUMNO (DNI) ON DELETE CASCADE,
    CONSTRAINT CK_TELEFONO_ALUMNO_TEL CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{9}$'))
