-- 3.1 Vista NO actualizable (2 tablas, GROUP BY y funciones agregadas):
--     expediente resumido de CADA alumno, con o sin evaluaciones (LEFT JOIN):
--     un alumno sin notas aparece con 0 asignaturas, 0 evaluaciones y media NULL.
--     NUM_ASIGNATURAS = asignaturas distintas evaluadas (COUNT DISTINCT).
--     NUM_EVALUACIONES = filas de EVALUA (una por alumno y docencia).
--     NOTA_MEDIA = media de TODAS las evaluaciones del historial (todos los
--     cursos y docencias), no solo de las asignaturas distintas.
--     No es actualizable: cada fila agrega varias filas de EVALUA, y el DML
--     no puede traducirse de forma unívoca a las tablas base.
CREATE OR REPLACE VIEW V_NOTAS_ALUMNO
    (DNI_ALUMNO, NOMBRE_COMPLETO, NUM_ASIGNATURAS, NUM_EVALUACIONES, NOTA_MEDIA) AS
SELECT A.DNI,
       A.NOMBRE || ' ' || A.APELLIDOS,
       COUNT(DISTINCT E.COD_ASIGNATURA),
       COUNT(E.NOTA_FINAL),
       ROUND(AVG(E.NOTA_FINAL), 2)
FROM ALUMNO A
LEFT JOIN EVALUA E ON E.DNI_ALUMNO = A.DNI
GROUP BY A.DNI, A.NOMBRE, A.APELLIDOS;

-- 3.2 Vista actualizable (una sola tabla base, sin agregados, con clave
--     completa y WITH CHECK OPTION): gestión de los laboratorios.
CREATE OR REPLACE VIEW V_AULA_LABORATORIO (COD_EDIFICIO, NUM_AULA, CAPACIDAD, TIPO) AS
SELECT COD_EDIFICIO, NUM_AULA, CAPACIDAD, TIPO
FROM AULA
WHERE TIPO = 'LABORATORIO'
WITH CHECK OPTION CONSTRAINT CK_V_AULA_LABORATORIO;

-- 3.3 Vista del atributo DERIVADO antigüedad (RN-06): no se almacena, se calcula
--     a partir de FECHA_INGRESO (años completos). Una sola tabla base y clave
--     completa: NSS, FECHA_INGRESO y COD_DEPARTAMENTO son actualizables;
--     ANTIGUEDAD_ANIOS es una expresión y NO es actualizable (ORA-01733).
CREATE OR REPLACE VIEW V_PROFESOR_ANTIGUEDAD
    (NSS, FECHA_INGRESO, COD_DEPARTAMENTO, ANTIGUEDAD_ANIOS) AS
SELECT NSS,
       FECHA_INGRESO,
       COD_DEPARTAMENTO,
       TRUNC(MONTHS_BETWEEN(SYSDATE, FECHA_INGRESO) / 12)
FROM PROFESOR;

-- ============================================================================
-- 4. COMPROBACIONES
--    P_PRUEBA ejecuta una sentencia, fuerza la comprobación de las restricciones
--    diferidas (SET CONSTRAINTS ALL IMMEDIATE) y hace ROLLBACK.
--    Una prueba negativa solo es [OK] si se rechaza con el SQLCODE esperado
--    y, cuando se indica, por la restricción concreta (aparece en SQLERRM).
--      P_SQLCODE      : código esperado (p. ej. -2290 CHECK, -2291 FK padre
--                       inexistente, -2292 FK hijos existentes, -1 UNIQUE/PK,
--                       -1400 NOT NULL, -1732 vista no actualizable,
--                       -1402 WITH CHECK OPTION)
--      P_SQLCODE_ALT  : código alternativo aceptable (en borrados de padres
--                       con FK diferida Oracle puede informar -2291 o -2292)
--      P_RESTRICCION  : nombre de la restricción (o columna) que debe aparecer
-- ============================================================================
CREATE OR REPLACE PROCEDURE P_PRUEBA(
    P_DESC          VARCHAR2,
    P_SQL           VARCHAR2,
    P_DEBE_FALLAR   NUMBER,
    P_SQLCODE       NUMBER   DEFAULT NULL,
    P_RESTRICCION   VARCHAR2 DEFAULT NULL,
    P_SQLCODE_ALT   NUMBER   DEFAULT NULL) IS
    V_CODE NUMBER;
    V_MSG  VARCHAR2(4000);
BEGIN
    EXECUTE IMMEDIATE P_SQL;
    EXECUTE IMMEDIATE 'SET CONSTRAINTS ALL IMMEDIATE';   -- fuerza las FK diferidas
    ROLLBACK;
    IF P_DEBE_FALLAR = 1 THEN
        DBMS_OUTPUT.PUT_LINE('[ERROR] No se rechazó: ' || P_DESC);
    ELSE
        DBMS_OUTPUT.PUT_LINE('[OK]    Aceptada:  ' || P_DESC);
    END IF;
EXCEPTION WHEN OTHERS THEN
    V_CODE := SQLCODE;
    V_MSG  := SQLERRM;
    ROLLBACK;
    IF P_DEBE_FALLAR = 0 THEN
        DBMS_OUTPUT.PUT_LINE('[ERROR] Debía aceptarse: ' || P_DESC || '  -> ' || SUBSTR(V_MSG,1,120));
    ELSIF P_SQLCODE IS NOT NULL AND V_CODE <> P_SQLCODE
          AND (P_SQLCODE_ALT IS NULL OR V_CODE <> P_SQLCODE_ALT) THEN
        DBMS_OUTPUT.PUT_LINE('[ERROR] Rechazada con otro SQLCODE (' || V_CODE || ', esperado '
            || P_SQLCODE || '): ' || P_DESC || '  -> ' || SUBSTR(V_MSG,1,120));
    ELSIF P_RESTRICCION IS NOT NULL AND INSTR(UPPER(V_MSG), UPPER(P_RESTRICCION)) = 0 THEN
        DBMS_OUTPUT.PUT_LINE('[ERROR] Rechazada por otra restricción (esperada ' || P_RESTRICCION
            || '): ' || P_DESC || '  -> ' || SUBSTR(V_MSG,1,120));
    ELSE
        DBMS_OUTPUT.PUT_LINE('[OK]    Rechazada: ' || P_DESC || '  -> ' || SUBSTR(V_MSG,1,100));
    END IF;
END;
