-- ---- ALUMNO (DIRECCION = atributo compuesto) -------------------------------
-- TELEFONO_REF y DNI_TUTOR_REF: mínimos RN-01 (>= 1 teléfono) y (>= 1 tutela),
-- con FK diferidas (se crean tras TELEFONO_ALUMNO y TUTELA).
CREATE TABLE ALUMNO (
