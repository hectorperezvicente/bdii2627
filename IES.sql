-- ---- TUTELA (N:M ALUMNO - TUTOR_LEGAL) ------------------------------------
CREATE TABLE TUTELA (
    DNI_TUTOR   VARCHAR2(10),
    DNI_ALUMNO  VARCHAR2(10),
    CONSTRAINT PK_TUTELA PRIMARY KEY (DNI_TUTOR, DNI_ALUMNO),
    CONSTRAINT FK_TUTELA_TUTOR FOREIGN KEY (DNI_TUTOR)
        REFERENCES TUTOR_LEGAL (DNI_TUTOR) ON DELETE CASCADE,
    CONSTRAINT FK_TUTELA_ALUMNO FOREIGN KEY (DNI_ALUMNO)
        REFERENCES ALUMNO (DNI) ON DELETE CASCADE
